#!/usr/bin/env node
// Generates packages/ui/src/tokens.css from packages/ui/tokens.json.
// `--check` exits non-zero when the committed CSS is stale (used by `npm run check`).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "tokens.json"), "utf8"));
const out = join(root, "src/tokens.css");
const modes = Object.keys(tokens.modes);
const [defaultMode] = modes;

const valueFor = (entry, mode) => entry[mode] ?? entry.all;
const cssString = (s) => `"${String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

function modeBlock(mode, { includeStatic }) {
  const lines = [];
  for (const [name, entry] of Object.entries(tokens.color)) {
    if (!includeStatic && "all" in entry) continue;
    lines.push(`  --color-${name}: ${valueFor(entry, mode)};`);
  }
  for (const [name, entry] of Object.entries(tokens.brand)) {
    lines.push(`  --brand-${name}: ${cssString(valueFor(entry, mode))};`);
  }
  return lines;
}

const css = [];
css.push("/* Generated by packages/ui/scripts/tokens.mjs from tokens.json. Do not edit by hand. */");
css.push(`/* Modes: ${modes.map((m) => `${m} = ${tokens.modes[m]}`).join(" · ")} */`, "");
css.push(`:root,\n[data-theme="${defaultMode}"] {`);
css.push(...modeBlock(defaultMode, { includeStatic: true }));
for (const [k, v] of Object.entries(tokens.space)) css.push(`  --space-${k}: ${v}px;`);
for (const [k, v] of Object.entries(tokens.radius)) css.push(`  --radius-${k}: ${v}px;`);
for (const [k, v] of Object.entries(tokens.font)) css.push(`  --font-${k}: ${v};`);
for (const [k, t] of Object.entries(tokens.text)) {
  css.push(`  --text-${k}: ${t.weight} ${t.size}px/${t.lineHeight} var(--font-${t.family});`);
  css.push(`  --text-${k}-tracking: ${t.letterSpacing};`);
}
css.push("}", "");
for (const mode of modes.slice(1)) {
  css.push(`[data-theme="${mode}"] {`);
  css.push(...modeBlock(mode, { includeStatic: false }));
  css.push("}", "");
}
for (const [k, t] of Object.entries(tokens.text)) {
  const decl = [`font: var(--text-${k})`, `letter-spacing: var(--text-${k}-tracking)`];
  if (t.transform) decl.push(`text-transform: ${t.transform}`);
  css.push(`.t-${k} { ${decl.join("; ")}; }`);
}
const result = css.join("\n") + "\n";

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8").replaceAll("\r\n", "\n") : "";
  if (current !== result) {
    console.error("tokens.css is stale. Run `npm run tokens`.");
    process.exit(1);
  }
  console.log("tokens.css is up to date.");
} else {
  writeFileSync(out, result);
  console.log(`Wrote ${out} (${modes.length} modes).`);
}
